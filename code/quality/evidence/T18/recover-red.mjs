import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {parseEnv} from 'node:util';
const source='C:/Users/PC/.gemini/antigravity-cli/brain/602267e4-860d-4c60-903f-74a5e9efc10f/.system_generated/logs/transcript.jsonl';
const rows=fs.readFileSync(source,'utf8').trim().split(/\r?\n/).map(x=>JSON.parse(x));
const launch=rows.find(x=>x.step_index===113),finish=rows.find(x=>x.step_index===119);
const command=launch.tool_calls.find(x=>x.name==='run_command').args.CommandLine;
assert(command.includes('npm run test --workspace @fg/api -- --runInBand test/rooms.integration.spec.ts'));
assert(finish.content.includes('The command exited with code 1.'));
const env=parseEnv(fs.readFileSync('.env.local','utf8'));
const secrets=Object.entries(env).filter(([k,v])=>/(SECRET|PASSWORD|PRIVATE_KEY)/.test(k)&&v.length>=8).map(([,v])=>v);
assert(!secrets.some(x=>finish.content.includes(x)),'Cannot persist transcript containing a configured secret');
const evidencePath='quality/evidence/T18/codex-recovered-red-transcript-119.txt';
assert(!fs.existsSync(evidencePath),'Preserve original evidence');
fs.writeFileSync(evidencePath,finish.content);
const record={command,cwd:launch.tool_calls[0].args.Cwd,startedAt:launch.created_at,completedAt:finish.created_at,exitCode:1,evidencePath,evidenceSha256:createHash('sha256').update(fs.readFileSync(evidencePath)).digest('hex'),source,sourceSteps:[113,119],note:'Recovered actual provider command output, with transcript truncation if any. Contains missing-room route404 RED plus dependent fixture failures; not PASS evidence.'};
fs.writeFileSync('quality/evidence/T18/codex-recovered-red-transcript-119.json',JSON.stringify(record,null,2)+'\n');
